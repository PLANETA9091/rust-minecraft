/// The smelting row (the None the no-recipe arm keeps).
pub fn smelt_result(id: i32) -> Option<(i32, i32)> {
    let i = usize::try_from(id).ok()?;
    let r = *SMELT_RESULT.get(i)?;
    if r == 0 {
        return None;
    }
    Some((r, SMELT_RESULT_COUNT[i]))
}

/// The fuel's burn duration (the 0 the not-fuel arm keeps).
pub fn fuel_ticks(id: i32) -> i32 {
    usize::try_from(id).ok().and_then(|i| FUEL_TICKS.get(i).copied()).unwrap_or(0)
}
