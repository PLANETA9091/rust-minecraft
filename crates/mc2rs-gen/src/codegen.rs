//! Codegen: write the generated registry + build info + report files.
//! Everything the client renders (registry, fonts, language, splashes,
//! GUI sprites, sounds, worldgen) is emitted here from official data.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::jar::JarReport;
use crate::soundgen::SoundData;
use crate::splashgen::SplashData;
use crate::fontgen::FontData;
use crate::langgen::LangData;
use crate::uigen::UiData;
use crate::worldgen::WorldgenData;
use crate::skygen::SkyData;

/// All extractor outputs for one version.
pub struct GenAll {
    pub font: FontData,
    pub lang: LangData,
    pub splashes: SplashData,
    pub ui: UiData,
    pub sounds: SoundData,
    pub worldgen: WorldgenData,
    pub sky: SkyData,
}

/// Write/refresh all generated Rust files for a version.
pub fn emit(
    workspace_root: &Path,
    version: &str,
    client_sha1: &str,
    report: &JarReport,
    gen: &GenAll,
) -> Result<std::path::PathBuf> {
    let reg_dir = workspace_root.join("crates/mc-registry/src/generated");
    fs::create_dir_all(&reg_dir)?;

    // ---- blocks.rs ----
    let mut blocks = String::with_capacity(64 * 1024);
    blocks.push_str(&format!(
        "// @generated by mc2rs-gen for Minecraft {version} — DO NOT EDIT BY HAND.\n\
         // Source of truth: official client jar blockstates (functional metadata only).\n\
         // Regenerate: `cargo run -p mc2rs-gen -- generate --version {version}`\n\
         use crate::Block;\n\n\
         pub static BLOCKS: &[Block] = &[\n"
    ));
    for b in &report.blocks {
        blocks.push_str(&format!("    Block {{ name: \"{}\", properties: &[", b.name));
        for (i, p) in b.properties.iter().enumerate() {
            if i > 0 {
                blocks.push_str(", ");
            }
            blocks.push_str(&format!("\"{p}\""));
        }
        blocks.push_str("] },\n");
    }
    blocks.push_str("];\n");
    fs::write(reg_dir.join("blocks.rs"), blocks).context("write blocks.rs")?;

    // ---- items.rs ----
    let mut items = String::with_capacity(16 * 1024);
    items.push_str(&format!(
        "// @generated by mc2rs-gen for Minecraft {version} — DO NOT EDIT BY HAND.\n\
         pub static ITEMS: &[&str] = &[\n"
    ));
    for it in &report.items {
        items.push_str(&format!("    \"{it}\",\n"));
    }
    items.push_str("];\n");
    fs::write(reg_dir.join("items.rs"), items).context("write items.rs")?;

    // ---- font.rs / lang.rs / splashes.rs / gui.rs / sounds.rs / worldgen.rs ----
    fs::write(reg_dir.join("font.rs"), crate::fontgen::emit(&gen.font)?).context("write font.rs")?;
    fs::write(reg_dir.join("lang.rs"), crate::langgen::emit(&gen.lang)?).context("write lang.rs")?;
    fs::write(reg_dir.join("splashes.rs"), crate::splashgen::emit(&gen.splashes)?)
        .context("write splashes.rs")?;
    fs::write(reg_dir.join("gui.rs"), crate::uigen::emit(&gen.ui)?).context("write gui.rs")?;
    fs::write(reg_dir.join("sounds.rs"), crate::soundgen::emit(&gen.sounds)?).context("write sounds.rs")?;
    fs::write(reg_dir.join("worldgen.rs"), crate::worldgen::emit(&gen.worldgen)?)
        .context("write worldgen.rs")?;
    fs::write(reg_dir.join("sky.rs"), crate::skygen::emit(&gen.sky)?).context("write sky.rs")?;

    // ---- build.rs (version stamp; deterministic — NO timestamps, CI drift-checks this) ----
    let build_info = format!(
        "// @generated by mc2rs-gen — DO NOT EDIT BY HAND.\n\
         pub const MINECRAFT_VERSION: &str = \"{version}\";\n\
         pub const CLIENT_SHA1: &str = \"{client_sha1}\";\n\
         pub const OBFUSCATED: bool = {};\n\
         /// Protocol version from the jar's embedded version.json (-1 if\n\
         /// none); the LOGIN handshake must speak this.\n\
         pub const PROTOCOL_VERSION: i32 = {};\n\
         /// World/data format version from version.json (-1 if unknown).\n\
         pub const WORLD_VERSION: i32 = {};\n",
        report.obfuscated,
        report.protocol_version.unwrap_or(-1),
        report.world_version.unwrap_or(-1)
    );
    fs::write(reg_dir.join("build.rs"), build_info).context("write build.rs")?;

    // ---- client build info ----
    let client_dir = workspace_root.join("crates/mc-client/src");
    fs::create_dir_all(&client_dir)?;
    let client_build = format!(
        "// @generated by mc2rs-gen — DO NOT EDIT BY HAND.\n\
         /// Target Minecraft version this client build tracks.\n\
         pub const MINECRAFT_VERSION: &str = \"{version}\";\n\
         /// sha1 of the official client jar the generator analyzed.\n\
         pub const CLIENT_SHA1: &str = \"{client_sha1}\";\n\
         /// True when the official jar is still obfuscated (pre-unobfuscation era).\n\
         pub const OBFUSCATED: bool = {};\n\
         /// Protocol version for the network layer (login handshake); -1 unknown.\n\
         pub const PROTOCOL_VERSION: i32 = {};\n",
        report.obfuscated,
        report.protocol_version.unwrap_or(-1)
    );
    fs::write(client_dir.join("build_info.rs"), client_build).context("write client build_info.rs")?;

    // ---- machine-readable report (for dashboards/CI) ----
    let report_json = serde_json::json!({
        "version": version,
        "clientSha1": client_sha1,
        "obfuscated": report.obfuscated,
        "obfuscationRatio": report.obfuscation_ratio,
        "protocolVersion": report.protocol_version,
        "worldVersion": report.world_version,
        "classes": report.class_count,
        "netMinecraftClasses": report.net_minecraft_classes,
        "blocks": report.blockstate_count,
        "items": report.item_count,
        "textures": report.texture_count,
        "sounds": report.sound_count,
        "hasLang": report.has_lang_en_us,
        "glyphs": gen.font.glyphs.len(),
        "fontTextures": gen.font.textures.len(),
        "langEntries": gen.lang.map.len(),
        "splashes": gen.splashes.lines.len(),
        "guiSprites": gen.ui.sprites.len(),
        "soundEvents": gen.sounds.events.len(),
        "biomes": gen.worldgen.biomes.len(),
        "noiseSettings": gen.worldgen.noise_settings.len(),
        "moonPhases": gen.sky.moon_phase_names.len(),
        "dayTimelineKeyframes": gen.sky.sun_angle.keyframes.len()
            + gen.sky.moon_angle.keyframes.len()
            + gen.sky.star_angle.keyframes.len()
            + gen.sky.star_brightness.keyframes.len(),
    });
    let report_path = workspace_root.join("mc2rs-report.json");
    fs::write(&report_path, serde_json::to_string_pretty(&report_json)?)
        .context("write mc2rs-report.json")?;

    Ok(report_path)
}

/// Extract runtime asset files (font textures, GUI sprites) from the jar
/// into `assets-cache/jar/` — the client loads real pixels from there at
/// runtime. Gitignored; regenerated by `generate`.
pub fn extract_runtime_assets(
    archive: &mut zip::ZipArchive<std::io::Cursor<&[u8]>>,
    workspace_root: &Path,
    ui: &UiData,
    font: &FontData,
) -> Result<usize> {
    use crate::extract::read_entry;
    let out_root = workspace_root.join("assets-cache/jar");
    let mut n = 0usize;
    for s in ui.sprites.values() {
        let jar_path = format!("assets/minecraft/textures/{}", s.file);
        let dest = out_root.join(&s.file);
        if dest.exists() {
            continue;
        }
        if let Ok(bytes) = read_entry(archive, &jar_path) {
            fs::create_dir_all(dest.parent().unwrap())?;
            fs::write(dest, bytes)?;
            n += 1;
        }
    }
    for t in &font.textures {
        // store under the same short path the generated FONT_TEXTURES uses
        let rel = t.strip_prefix("assets/minecraft/textures/").unwrap_or(t);
        let dest = out_root.join(rel);
        if dest.exists() {
            continue;
        }
        if let Ok(bytes) = read_entry(archive, t) {
            fs::create_dir_all(dest.parent().unwrap())?;
            fs::write(dest, bytes)?;
            n += 1;
        }
    }
    // The player skin (wide Steve): the first-person hand's pixel source,
    // streamed from the runtime root and sha1-verified by the client.
    {
        let dest = out_root.join(crate::skingen::RUNTIME_PATH);
        if !dest.exists() {
            if let Ok(bytes) = read_entry(archive, crate::skingen::WIDE_STEVE_JAR_PATH) {
                fs::create_dir_all(dest.parent().unwrap())?;
                fs::write(dest, bytes)?;
                n += 1;
            }
        }
    }
    // The slim (Alex) skin: the `--slim-arm` variant's pixel source, the
    // same sha1-verified stream pattern.
    {
        let dest = out_root.join(crate::skingen::SLIM_RUNTIME_PATH);
        if !dest.exists() {
            if let Ok(bytes) = read_entry(archive, crate::skingen::SLIM_ALEX_JAR_PATH) {
                fs::create_dir_all(dest.parent().unwrap())?;
                fs::write(dest, bytes)?;
                n += 1;
            }
        }
    }
    // The ZOMBIE skin: the first mob's pixel source, the same
    // sha1-verified stream pattern (javap: `AbstractZombieRenderer`'s
    // ZOMBIE_LOCATION — `textures/entity/zombie/zombie.png`).
    {
        let dest = out_root.join(crate::skingen::ZOMBIE_RUNTIME_PATH);
        if !dest.exists() {
            if let Ok(bytes) = read_entry(archive, crate::skingen::ZOMBIE_JAR_PATH) {
                fs::create_dir_all(dest.parent().unwrap())?;
                fs::write(dest, bytes)?;
                n += 1;
            }
        }
    }
    // The FIRE strips: the flame feature's pixel sources —
    // `FlameFeatureRenderer.buildGroup` pulls `block/fire_0` and
    // `block/fire_1` off the blocks atlas (javap: ModelBakery.FIRE_0 /
    // FIRE_1 sprite ids); the 16x512 strips ride the animated frame
    // tiles the burn lane samples (fire_0's mcmeta playlist
    // [16..31, 0..15], fire_1 sequential). The WATER screen's texture
    // rides beside them (javap `ScreenEffectRenderer.submitWater`'s
    // UNDERWATER_LOCATION — `textures/misc/underwater.png`, the 16x16
    // blue the eye-under-water pass tiles across the screen). The same
    // sha1-verified stream pattern the skins speak.
    {
        for jar_rel in RUNTIME_TEXTURE_JAR_PATHS {
            // the runtime path mirrors the jar path minus the textures
            // prefix (`assets/minecraft/textures/` — the same strip the
            // other texture lanes keep)
            let rel = jar_rel
                .strip_prefix("assets/minecraft/textures/")
                .unwrap_or(jar_rel);
            let dest = out_root.join(rel);
            if dest.exists() {
                continue;
            }
            if let Ok(bytes) = read_entry(archive, jar_rel) {
                fs::create_dir_all(dest.parent().unwrap())?;
                fs::write(dest, bytes)?;
                n += 1;
            }
        }
    }
    Ok(n)
}

/// The flame feature's two animated strips, straight from the jar's
/// `assets/minecraft/textures/block/` — the runtime pixel sources the
/// client sha1-verifies before it draws a burning mob. The water
/// screen's texture rides beside them (the underwater overlay's pixel
/// source, `textures/misc/underwater.png`).
const RUNTIME_TEXTURE_JAR_PATHS: [&str; 3] = [
    "assets/minecraft/textures/block/fire_0.png",
    "assets/minecraft/textures/block/fire_1.png",
    "assets/minecraft/textures/misc/underwater.png",
];
