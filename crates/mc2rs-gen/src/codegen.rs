//! Codegen: write the generated registry + build info + report files.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::jar::JarReport;

/// Write/refresh all generated Rust files for a version.
pub fn emit(
    workspace_root: &Path,
    version: &str,
    client_sha1: &str,
    report: &JarReport,
) -> Result<std::path::PathBuf> {
    let reg_dir = workspace_root.join("crates/mc-registry/src/generated");
    fs::create_dir_all(&reg_dir)?;

    // ---- blocks.rs ----
    let mut blocks = String::with_capacity(64 * 1024);
    blocks.push_str(&format!(
        "// @generated by mc2rs-gen for Minecraft {version} — DO NOT EDIT BY HAND.\n\
         // Source of truth: official client jar blockstates (functional metadata only).\n\
         // Regenerate: `cargo run -p mc2rs-gen -- generate --version {version}`\n\
         use crate::Block;\n\n\
         pub static BLOCKS: &[Block] = &[\n"
    ));
    for b in &report.blocks {
        blocks.push_str(&format!("    Block {{ name: \"{}\", properties: &[", b.name));
        for (i, p) in b.properties.iter().enumerate() {
            if i > 0 {
                blocks.push_str(", ");
            }
            blocks.push_str(&format!("\"{p}\""));
        }
        blocks.push_str("] },\n");
    }
    blocks.push_str("];\n");
    fs::write(reg_dir.join("blocks.rs"), blocks).context("write blocks.rs")?;

    // ---- items.rs ----
    let mut items = String::with_capacity(16 * 1024);
    items.push_str(&format!(
        "// @generated by mc2rs-gen for Minecraft {version} — DO NOT EDIT BY HAND.\n\
         pub static ITEMS: &[&str] = &[\n"
    ));
    for it in &report.items {
        items.push_str(&format!("    \"{it}\",\n"));
    }
    items.push_str("];\n");
    fs::write(reg_dir.join("items.rs"), items).context("write items.rs")?;

    // ---- build.rs (version stamp; deterministic — NO timestamps, CI drift-checks this) ----
    let build_info = format!(
        "// @generated by mc2rs-gen — DO NOT EDIT BY HAND.\n\
         pub const MINECRAFT_VERSION: &str = \"{version}\";\n\
         pub const CLIENT_SHA1: &str = \"{client_sha1}\";\n\
         pub const OBFUSCATED: bool = {};\n",
        report.obfuscated
    );
    fs::write(reg_dir.join("build.rs"), build_info).context("write build.rs")?;

    // ---- client build info ----
    let client_dir = workspace_root.join("crates/mc-client/src");
    fs::create_dir_all(&client_dir)?;
    let client_build = format!(
        "// @generated by mc2rs-gen — DO NOT EDIT BY HAND.\n\
         /// Target Minecraft version this client build tracks.\n\
         pub const MINECRAFT_VERSION: &str = \"{version}\";\n\
         /// sha1 of the official client jar the generator analyzed.\n\
         pub const CLIENT_SHA1: &str = \"{client_sha1}\";\n\
         /// True when the official jar is still obfuscated (pre-unobfuscation era).\n\
         pub const OBFUSCATED: bool = {};\n",
        report.obfuscated
    );
    fs::write(client_dir.join("build_info.rs"), client_build).context("write client build_info.rs")?;

    // ---- machine-readable report (for dashboards/CI) ----
    let report_json = serde_json::json!({
        "version": version,
        "clientSha1": client_sha1,
        "obfuscated": report.obfuscated,
        "obfuscationRatio": report.obfuscation_ratio,
        "classes": report.class_count,
        "netMinecraftClasses": report.net_minecraft_classes,
        "blocks": report.blockstate_count,
        "items": report.item_count,
        "textures": report.texture_count,
        "sounds": report.sound_count,
        "hasLang": report.has_lang_en_us,
    });
    let report_path = workspace_root.join("mc2rs-report.json");
    fs::write(&report_path, serde_json::to_string_pretty(&report_json)?)
        .context("write mc2rs-report.json")?;

    Ok(report_path)
}
