//! Splash text generation: every line of the official `texts/splashes.txt`.

use anyhow::Result;

use crate::extract::read_entry;

pub struct SplashData {
    pub lines: Vec<String>,
}

pub fn generate<R: std::io::Read + std::io::Seek>(archive: &mut zip::ZipArchive<R>) -> Result<SplashData> {
    let bytes = read_entry(archive, "assets/minecraft/texts/splashes.txt")?;
    let text = String::from_utf8_lossy(&bytes);
    let lines: Vec<String> = text
        .split('\n')
        .map(|l| l.trim_end_matches('\r').to_string())
        .filter(|l| !l.is_empty())
        .collect();
    Ok(SplashData { lines })
}

fn rust_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 8);
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

pub fn emit(data: &SplashData) -> Result<String> {
    let mut out = String::with_capacity(64 << 10);
    out.push_str("//! GENERATED by mc2rs-gen from the official texts/splashes.txt.\n\n");
    out.push_str("pub static SPLASHES: [&str; ");
    out.push_str(&data.lines.len().to_string());
    out.push_str("] = [\n");
    for l in &data.lines {
        out.push_str("    \"");
        out.push_str(&rust_escape(l));
        out.push_str("\",\n");
    }
    out.push_str("];\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn zip_of(entries: &[(&str, Vec<u8>)]) -> zip::ZipArchive<std::io::Cursor<Vec<u8>>> {
        let mut buf = std::io::Cursor::new(Vec::new());
        {
            let mut w = zip::ZipWriter::new(&mut buf);
            let opts = zip::write::SimpleFileOptions::default();
            for (name, data) in entries {
                w.start_file(*name, opts).unwrap();
                std::io::Write::write_all(&mut w, data).unwrap();
            }
            w.finish().unwrap();
        }
        zip::ZipArchive::new(buf).unwrap()
    }

    #[test]
    fn parses_and_skips_empty_lines() {
        let mut txt = b"As seen on TV!\nAwesome!\n\n100% pure!\n".to_vec();
        txt.push(b'\r');
        txt.extend_from_slice(b"\nMore polygons!\n");
        let mut zip = zip_of(&[("assets/minecraft/texts/splashes.txt", txt)]);
        let data = generate(&mut zip).unwrap();
        assert_eq!(data.lines, vec!["As seen on TV!", "Awesome!", "100% pure!", "More polygons!"]);
        let emitted = emit(&data).unwrap();
        assert!(emitted.contains("pub static SPLASHES: [&str; 4]"));
        assert!(emitted.contains("\"As seen on TV!\""));
    }
}
