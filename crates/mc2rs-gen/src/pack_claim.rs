//! Pack-claim generation: parses the jar's root `version.json` (the
//! manifest the vanilla `WorldVersion` record is built from) and emits the
//! generated constants the protocol layer's Select Known Packs reply is
//! built from — the pack-version claim arc's data half.
//!
//! THE CLAIM SHAPE (javap-proven 26.2, `tools/client.jar`):
//! - `BuiltInPackSource.<clinit>`: `CORE_PACK_INFO = KnownPack.vanilla("core")`
//! - `KnownPack.vanilla(String id)`:
//!   `new KnownPack("minecraft", id, SharedConstants.getCurrentVersion().id())`
//!   — so the record the vanilla client sends is
//!   `("minecraft", "core", WorldVersion.id())` and the VERSION STRING is
//!   the version.json `id` field ("26.2"), NOT the pack-format number
//!   (version.json's pack_version carries the separate
//!   `{resource_major,resource_minor,data_major,data_minor}` surface).
//!
//! The generated file carries ONLY what the jar itself says; the wire
//! shape (the namespace "minecraft" / id "core" pair) lives in the hand
//! code beside the protocol with the full proof chain.

use anyhow::{bail, Context, Result};
use serde_json::Value;
use zip::ZipArchive;

use crate::extract::read_entry;

/// The manifest surface the claim is built from — every field the 26.2
/// version.json carries and the emitter knows how to represent.
#[derive(Debug, Clone)]
pub struct PackClaim {
    /// version.json `id` — the KnownPack version string (the javap proof
    /// above: `WorldVersion.id()` is what the vanilla client sends).
    pub id: String,
    /// version.json `name` — the human-facing version name.
    pub name: String,
    /// version.json `world_version` — the data version.
    pub world_version: i64,
    /// version.json `protocol_version`.
    pub protocol_version: i32,
    /// version.json `pack_version` — the four-field 26.2 schema.
    pub resource_major: i32,
    pub resource_minor: i32,
    pub data_major: i32,
    pub data_minor: i32,
}

/// Parse the jar's root version.json into a [`PackClaim`]. Refuses a jar
/// without the manifest, an empty id, or a pack_version that does not
/// carry the full four-field schema — guessing a shape the jar does not
/// state would put a lie on the wire.
pub fn generate<R: std::io::Read + std::io::Seek>(
    archive: &mut ZipArchive<R>,
) -> Result<PackClaim> {
    let bytes = read_entry(archive, "version.json")
        .context("version.json not found in jar root (not a vanilla client jar?)")?;
    let json: Value =
        serde_json::from_slice(&bytes).context("version.json is not valid JSON")?;

    let id = json
        .get("id")
        .and_then(Value::as_str)
        .context("version.json has no string id")?
        .to_string();
    if id.is_empty() {
        bail!("version.json id is empty — the KnownPack version would be a lie");
    }
    let name = json
        .get("name")
        .and_then(Value::as_str)
        .context("version.json has no string name")?
        .to_string();
    let world_version = json
        .get("world_version")
        .and_then(Value::as_i64)
        .context("version.json has no numeric world_version")?;
    let protocol_version = json
        .get("protocol_version")
        .and_then(Value::as_i64)
        .context("version.json has no numeric protocol_version")?
        .try_into()
        .context("protocol_version does not fit i32")?;

    // the 26.2 schema: pack_version is an object with the four major/minor
    // counters (the pre-26.x {resource, data} pair and the bare-int schema
    // are refused — emit what the jar states, nothing inferred)
    let pv = json
        .get("pack_version")
        .context("version.json has no pack_version")?;
    let obj = pv
        .as_object()
        .context("version.json pack_version is not an object (the 26.2 four-field schema)")?;
    let mut fields = [0i32; 4];
    for (slot, key) in fields.iter_mut().zip([
        "resource_major",
        "resource_minor",
        "data_major",
        "data_minor",
    ]) {
        let v = obj
            .get(key)
            .and_then(Value::as_i64)
            .with_context(|| format!("version.json pack_version.{key} missing or not numeric"))?;
        *slot = v.try_into().with_context(|| format!("pack_version.{key} does not fit i32"))?;
    }
    let [resource_major, resource_minor, data_major, data_minor] = fields;

    Ok(PackClaim {
        id,
        name,
        world_version,
        protocol_version,
        resource_major,
        resource_minor,
        data_major,
        data_minor,
    })
}

/// Emit the generated `mc-protocol/src/generated/pack_claim.rs`.
pub fn emit(claim: &PackClaim) -> Result<String> {
    let mut out = String::new();
    out.push_str(&format!(
        "//! Generated by `mc2rs-gen pack-claim` from the jar's version.json — \
DO NOT EDIT BY HAND.\n\
//! The manifest the vanilla `WorldVersion` record is built from; the \
Select Known\n\
//! Packs reply's version string is `WorldVersion.id()` (javap-proven: \
`KnownPack.vanilla(\"core\")`\n\
//! passes `SharedConstants.getCurrentVersion().id()` — the record is \
(\"minecraft\", \"core\", id)).\n\
//! Source version: {}\n\n",
        claim.id
    ));
    out.push_str("/// version.json `id` — the KnownPack version string the vanilla client sends.\n");
    out.push_str(&format!("pub const VERSION_ID: &str = {:?};\n\n", claim.id));
    out.push_str("/// version.json `name` — the human-facing version name.\n");
    out.push_str(&format!("pub const VERSION_NAME: &str = {:?};\n\n", claim.name));
    out.push_str("/// version.json `world_version` — the data version.\n");
    out.push_str(&format!("pub const WORLD_VERSION: i64 = {};\n\n", claim.world_version));
    out.push_str("/// version.json `protocol_version`.\n");
    out.push_str(&format!(
        "pub const PROTOCOL_VERSION: i32 = {};\n\n",
        claim.protocol_version
    ));
    out.push_str("/// version.json `pack_version` — the 26.2 four-field schema.\n");
    out.push_str(&format!(
        "pub const PACK_VERSION_RESOURCE_MAJOR: i32 = {};\npub const PACK_VERSION_RESOURCE_MINOR: i32 = {};\npub const PACK_VERSION_DATA_MAJOR: i32 = {};\npub const PACK_VERSION_DATA_MINOR: i32 = {};\n",
        claim.resource_major, claim.resource_minor, claim.data_major, claim.data_minor
    ));
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Cursor;

    const REAL_VERSION_JSON: &str = r##"{
        "id": "26.2",
        "name": "26.2",
        "world_version": 4903,
        "series_id": "main",
        "protocol_version": 776,
        "pack_version": {
            "resource_major": 88,
            "resource_minor": 0,
            "data_major": 107,
            "data_minor": 1
        },
        "build_time": "2026-06-16T12:01:27+00:00",
        "java_component": "java-runtime-epsilon",
        "java_version": 25,
        "stable": true
    }"##;

    fn fixture_zip(entries: &[(&str, &str)]) -> ZipArchive<Cursor<Vec<u8>>> {
        let mut buf = Cursor::new(Vec::new());
        {
            let mut w = zip::ZipWriter::new(&mut buf);
            let opts: zip::write::FileOptions<'_, ()> = zip::write::FileOptions::default();
            for (name, body) in entries {
                w.start_file(*name, opts.clone()).unwrap();
                std::io::Write::write_all(&mut w, body.as_bytes()).unwrap();
            }
            w.finish().unwrap();
        }
        ZipArchive::new(buf).unwrap()
    }

    #[test]
    fn parses_the_real_version_json_surface() {
        let mut z = fixture_zip(&[("version.json", REAL_VERSION_JSON)]);
        let claim = generate(&mut z).expect("the real manifest parses");
        assert_eq!(claim.id, "26.2");
        assert_eq!(claim.name, "26.2");
        assert_eq!(claim.world_version, 4903);
        assert_eq!(claim.protocol_version, 776);
        assert_eq!(
            (
                claim.resource_major,
                claim.resource_minor,
                claim.data_major,
                claim.data_minor
            ),
            (88, 0, 107, 1)
        );

        let src = emit(&claim).unwrap();
        assert!(src.contains("pub const VERSION_ID: &str = \"26.2\";"));
        assert!(src.contains("pub const WORLD_VERSION: i64 = 4903;"));
        assert!(src.contains("pub const PROTOCOL_VERSION: i32 = 776;"));
        assert!(src.contains("pub const PACK_VERSION_DATA_MAJOR: i32 = 107;"));
        assert!(src.contains("Generated by `mc2rs-gen pack-claim`"));
        // the emitted constants must re-parse to the same claim (the
        // round-trip the checked-in file lives or dies by)
        assert!(claim.id.len() > 0, "a non-empty id IS the claim");
    }

    #[test]
    fn refuses_manifests_that_do_not_state_the_full_surface() {
        // no version.json at all
        let mut z = fixture_zip(&[("other.txt", "x")]);
        assert!(generate(&mut z).is_err(), "a jar without the manifest is refused");

        // an empty id would put a lie on the wire
        let mut z = fixture_zip(&[(
            "version.json",
            r#"{"id":"","name":"26.2","world_version":4903,"protocol_version":776,
                "pack_version":{"resource_major":88,"resource_minor":0,"data_major":107,"data_minor":1}}"#,
        )]);
        assert!(generate(&mut z).is_err(), "an empty id is refused");

        // the pre-26.x two-field pack_version shape is refused, not guessed
        let mut z = fixture_zip(&[(
            "version.json",
            r#"{"id":"26.2","name":"26.2","world_version":4903,"protocol_version":776,
                "pack_version":{"resource":88,"data":107}}"#,
        )]);
        assert!(generate(&mut z).is_err(), "the legacy pack_version schema is refused");

        // a missing field inside the four-field object
        let mut z = fixture_zip(&[(
            "version.json",
            r#"{"id":"26.2","name":"26.2","world_version":4903,"protocol_version":776,
                "pack_version":{"resource_major":88,"resource_minor":0,"data_major":107}}"#,
        )]);
        assert!(generate(&mut z).is_err(), "a partial pack_version is refused");
    }
}
