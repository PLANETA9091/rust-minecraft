//! Sound generation: parses the official `sounds.json` (delivered through
//! the asset index, not inside the jar) into a Rust sound-event table used
//! by the music/sound scheduler.

use std::collections::BTreeMap;

use anyhow::{Context, Result};
use serde_json::Value;

#[derive(Debug, Clone)]
pub struct SoundFile {
    /// path as given by sounds.json ("music/menu/menu1")
    pub name: String,
    pub volume: f32,
    pub pitch: f32,
    pub weight: u32,
    pub stream: bool,
}

#[derive(Debug, Clone)]
pub struct SoundEvent {
    pub id: String,
    pub subtitle: Option<String>,
    pub files: Vec<SoundFile>,
}

#[derive(Debug, Default)]
pub struct SoundData {
    pub events: BTreeMap<String, SoundEvent>,
}

impl SoundData {
    pub fn event(&self, id: &str) -> Option<&SoundEvent> {
        self.events.get(id)
    }

    /// All events under a namespace prefix, sorted ("music.menu." etc).
    pub fn events_with_prefix(&self, prefix: &str) -> Vec<&SoundEvent> {
        self.events
            .values()
            .filter(|e| e.id.starts_with(prefix))
            .collect()
    }
}

pub fn generate(bytes: &[u8]) -> Result<SoundData> {
    let v: Value = serde_json::from_slice(bytes).context("sounds.json parse")?;
    let obj = v.as_object().context("sounds.json is not an object")?;
    let mut data = SoundData::default();
    for (id, ev) in obj {
        let subtitle = ev.get("subtitle").and_then(Value::as_str).map(String::from);
        let mut files = Vec::new();
        match ev.get("sounds") {
            Some(Value::Array(list)) => {
                for s in list {
                    match s {
                        Value::String(name) => files.push(SoundFile {
                            name: name.clone(),
                            volume: 1.0,
                            pitch: 1.0,
                            weight: 1,
                            stream: false,
                        }),
                        Value::Object(o) => {
                            let Some(name) = o.get("name").and_then(Value::as_str) else { continue };
                            files.push(SoundFile {
                                name: name.to_string(),
                                volume: o.get("volume").and_then(Value::as_f64).unwrap_or(1.0) as f32,
                                pitch: o.get("pitch").and_then(Value::as_f64).unwrap_or(1.0) as f32,
                                weight: o.get("weight").and_then(Value::as_u64).unwrap_or(1) as u32,
                                stream: o.get("stream").and_then(Value::as_bool).unwrap_or(false),
                            })
                        }
                        _ => {}
                    }
                }
            }
            _ => {}
        }
        data.events.insert(id.clone(), SoundEvent { id: id.clone(), subtitle, files });
    }
    Ok(data)
}

fn f(x: f32) -> String {
    if x == x.trunc() && x.abs() < 1e6 {
        format!("{}", x as i64)
    } else {
        format!("{x}")
    }
}

fn rust_str(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

pub fn emit(data: &SoundData) -> Result<String> {
    let total_files: usize = data.events.values().map(|e| e.files.len()).sum();
    let mut out = String::with_capacity(256 << 10);
    out.push_str("//! GENERATED by mc2rs-gen from the official sounds.json (asset index).\n\n");

    out.push_str("#[derive(Debug, Clone, Copy, PartialEq)]\npub struct SoundFileDef {\n    pub name: &'static str,\n    pub volume: f32,\n    pub pitch: f32,\n    pub weight: u32,\n    pub stream: bool,\n}\n\n");
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq)]\npub struct SoundEventDef {\n    pub id: &'static str,\n    pub subtitle: Option<&'static str>,\n    pub first: usize,\n    pub len: usize,\n}\n\n");

    out.push_str("static SOUND_FILES: [SoundFileDef; ");
    out.push_str(&total_files.to_string());
    out.push_str("] = [\n");
    let mut idx = 0usize;
    let mut spans: Vec<(String, Option<String>, usize, usize)> = Vec::new();
    for ev in data.events.values() {
        let first = idx;
        for fl in &ev.files {
            out.push_str(&format!(
                "    SoundFileDef {{ name: \"{}\", volume: {}, pitch: {}, weight: {}, stream: {} }},\n",
                rust_str(&fl.name),
                f(fl.volume),
                f(fl.pitch),
                fl.weight,
                fl.stream
            ));
            idx += 1;
        }
        spans.push((
            ev.id.clone(),
            ev.subtitle.clone(),
            first,
            ev.files.len(),
        ));
    }
    out.push_str("];\n\n");

    out.push_str("pub static SOUND_EVENTS: [SoundEventDef; ");
    out.push_str(&data.events.len().to_string());
    out.push_str("] = [\n");
    for (id, sub, first, len) in &spans {
        let s = match sub {
            Some(s) => format!("Some(\"{}\")", rust_str(s)),
            None => "None".to_string(),
        };
        out.push_str(&format!(
            "    SoundEventDef {{ id: \"{}\", subtitle: {}, first: {}, len: {} }},\n",
            rust_str(id),
            s,
            first,
            len
        ));
    }
    out.push_str("];\n\n");

    out.push_str("/// Lookup a sound event by id.\npub fn event(id: &str) -> Option<&'static SoundEventDef> {\n");
    out.push_str("    SOUND_EVENTS.binary_search_by_key(&id, |e| e.id).ok().map(|i| &SOUND_EVENTS[i])\n}\n\n");
    out.push_str("/// Files of an event.\npub fn files(e: &'static SoundEventDef) -> &'static [SoundFileDef] {\n");
    out.push_str("    &SOUND_FILES[e.first..e.first + e.len]\n}\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_string_and_object_sounds() {
        let json = br#"{
            "music.menu.menu1": {"sounds":[{"name":"music/menu/menu1","stream":true,"volume":0.5}]},
            "ui.button.click": {"sounds":["click1","click2"],"subtitle":"subtitles.ui.click"}
        }"#;
        let data = generate(json).unwrap();
        assert_eq!(data.events.len(), 2);
        let m = data.event("music.menu.menu1").unwrap();
        assert_eq!(m.files.len(), 1);
        assert!(m.files[0].stream);
        assert_eq!(m.files[0].volume, 0.5);
        let ui = data.event("ui.button.click").unwrap();
        assert_eq!(ui.subtitle.as_deref(), Some("subtitles.ui.click"));
        assert_eq!(ui.files[1].name, "click2");
        assert_eq!(ui.files[1].volume, 1.0);

        let menu = data.events_with_prefix("music.menu.");
        assert_eq!(menu.len(), 1);

        let emitted = emit(&data).unwrap();
        assert!(emitted.contains("id: \"music.menu.menu1\""));
        assert!(emitted.contains("volume: 0.5"));
        assert!(emitted.contains("pub fn event(id: &str)"));
    }
}
