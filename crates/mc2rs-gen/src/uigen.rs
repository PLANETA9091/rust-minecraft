//! GUI sprite generation: walks `textures/gui/sprites/**` in the jar, records
//! every sprite's real pixel size (PNG IHDR) and scaling metadata (.mcmeta —
//! nine_slice borders). Extra title-screen textures that ship through the
//! asset index (title panorama, studio logo) are merged in by the caller.

use std::collections::BTreeMap;

use anyhow::Result;

use crate::extract::{parse_sprite_mcmeta, png_size, read_entry};

#[derive(Debug, Clone)]
pub struct Sprite {
    /// registry name: relative path without extension ("widget/button")
    pub name: String,
    /// file path under assets/minecraft/textures/ ("gui/sprites/widget/button.png")
    pub file: String,
    pub w: u32,
    pub h: u32,
    /// nine_slice metadata: (target_w, target_h, border)
    pub nine_slice: Option<(u32, u32, u32)>,
}

#[derive(Debug, Default)]
pub struct UiData {
    pub sprites: BTreeMap<String, Sprite>,
}

const SPRITES_ROOT: &str = "assets/minecraft/textures/gui/sprites/";
/// Title-screen textures are registered from the `gui/` root so the names
/// keep their "title/" prefix ("title/minecraft"). In 26.2 the panorama PNGs
/// in the jar are 1x1 placeholders; the real pixels stream via the asset
/// index (merged in by the caller). The logo textures are real in-jar.
const GUI_ROOT: &str = "assets/minecraft/textures/gui/";
const TITLE_ROOT: &str = "assets/minecraft/textures/gui/title/";

pub fn generate<R: std::io::Read + std::io::Seek>(archive: &mut zip::ZipArchive<R>) -> Result<UiData> {
    let mut data = UiData::default();
    let names: Vec<String> = archive
        .file_names()
        .filter(|n| n.starts_with(SPRITES_ROOT) && n.ends_with(".png"))
        .map(String::from)
        .collect();
    for path in names {
        let bytes = read_entry(archive, &path)?;
        let (w, h) = png_size(&bytes)?;
        let rel = &path[SPRITES_ROOT.len()..path.len() - ".png".len()];
        let mcmeta_path = format!("{path}.mcmeta");
        let nine_slice = match read_entry(archive, &mcmeta_path) {
            Ok(mb) => parse_sprite_mcmeta(&mb)?.nine_slice,
            Err(_) => None,
        };
        data.sprites.insert(
            rel.to_string(),
            Sprite {
                name: rel.to_string(),
                file: format!("gui/sprites/{rel}.png"),
                w,
                h,
                nine_slice,
            },
        );
    }
    // Title textures: registry names like "title/minecraft",
    // "title/background/panorama_0"; files "gui/title/....png".
    let title_names: Vec<String> = archive
        .file_names()
        .filter(|n| n.starts_with(TITLE_ROOT) && n.ends_with(".png"))
        .map(String::from)
        .collect();
    for path in title_names {
        let bytes = read_entry(archive, &path)?;
        let (w, h) = png_size(&bytes)?;
        let rel = &path[GUI_ROOT.len()..path.len() - ".png".len()];
        data.sprites.entry(rel.to_string()).or_insert_with(|| Sprite {
            name: rel.to_string(),
            file: format!("gui/{rel}.png"),
            w,
            h,
            nine_slice: None,
        });
    }
    Ok(data)
}

/// Merge sprites discovered outside the jar (asset index downloads, e.g.
/// the real title panorama). Files must exist on disk. With `overwrite`,
/// on-disk entries replace jar-inventoried placeholders (the 26.2 jar ships
/// 1x1 panorama stubs); with `overwrite=false` existing entries win.
pub fn merge_from_disk(
    data: &mut UiData,
    root: &std::path::Path,
    names: &[(String, String)],
    overwrite: bool,
) -> Result<()> {
    for (rel_name, rel_file) in names {
        let path = root.join(rel_file);
        let Ok(bytes) = std::fs::read(&path) else { continue };
        let (w, h) = png_size(&bytes)?;
        let exists = data.sprites.contains_key(rel_name);
        if exists && !overwrite {
            continue;
        }
        data.sprites.insert(
            rel_name.clone(),
            Sprite {
                name: rel_name.clone(),
                file: rel_file.clone(),
                w,
                h,
                nine_slice: None,
            },
        );
    }
    Ok(())
}

fn rust_str(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

pub fn emit(data: &UiData) -> Result<String> {
    let mut out = String::with_capacity(128 << 10);
    out.push_str("//! GENERATED by mc2rs-gen from the official GUI sprite inventory.\n");
    out.push_str("//! Sizes are the real PNG dimensions; nine_slice borders come from .mcmeta.\n\n");

    out.push_str("#[derive(Debug, Clone, Copy, PartialEq)]\npub struct SpriteDef {\n    pub name: &'static str,\n    pub file: &'static str,\n    pub w: u32,\n    pub h: u32,\n    /// (target_w, target_h, border) when the sprite declares nine_slice scaling\n    pub nine_slice: Option<(u32, u32, u32)>,\n}\n\n");

    out.push_str("pub static SPRITES: [SpriteDef; ");
    out.push_str(&data.sprites.len().to_string());
    out.push_str("] = [\n");
    for s in data.sprites.values() {
        let ns = match s.nine_slice {
            Some((w, h, b)) => format!("Some(({}, {}, {}))", w, h, b),
            None => "None".to_string(),
        };
        out.push_str(&format!(
            "    SpriteDef {{ name: \"{}\", file: \"{}\", w: {}, h: {}, nine_slice: {} }},\n",
            rust_str(&s.name),
            rust_str(&s.file),
            s.w,
            s.h,
            ns
        ));
    }
    out.push_str("];\n\n");

    out.push_str("/// Lookup a sprite by registry name (\"widget/button\").\n");
    out.push_str("pub fn sprite(name: &str) -> Option<&'static SpriteDef> {\n");
    out.push_str("    SPRITES.binary_search_by_key(&name, |s| s.name).ok().map(|i| &SPRITES[i])\n}\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tiny_png(w: u32, h: u32) -> Vec<u8> {
        let rgba = vec![255u8; (w * h * 4) as usize];
        let mut out = Vec::new();
        {
            let mut enc = png::Encoder::new(&mut out, w, h);
            enc.set_color(png::ColorType::Rgba);
            enc.set_depth(png::BitDepth::Eight);
            let mut wr = enc.write_header().unwrap();
            wr.write_image_data(&rgba).unwrap();
        }
        out
    }

    fn zip_of(entries: &[(&str, Vec<u8>)]) -> zip::ZipArchive<std::io::Cursor<Vec<u8>>> {
        let mut buf = std::io::Cursor::new(Vec::new());
        {
            let mut w = zip::ZipWriter::new(&mut buf);
            let opts = zip::write::SimpleFileOptions::default();
            for (name, data) in entries {
                w.start_file(*name, opts).unwrap();
                std::io::Write::write_all(&mut w, data).unwrap();
            }
            w.finish().unwrap();
        }
        zip::ZipArchive::new(buf).unwrap()
    }

    #[test]
    fn inventories_sprites_with_nine_slice() {
        let mut zip = zip_of(&[
            (
                "assets/minecraft/textures/gui/sprites/widget/button.png",
                tiny_png(200, 20),
            ),
            (
                "assets/minecraft/textures/gui/sprites/widget/button.png.mcmeta",
                br#"{"gui":{"scaling":{"type":"nine_slice","width":200,"height":20,"border":3}}}"#.to_vec(),
            ),
            (
                "assets/minecraft/textures/gui/sprites/hud/crosshair.png",
                tiny_png(15, 15),
            ),
            ("assets/minecraft/textures/other/ignored.png", tiny_png(1, 1)),
        ]);
        let data = generate(&mut zip).unwrap();
        assert_eq!(data.sprites.len(), 2);
        let b = &data.sprites["widget/button"];
        assert_eq!((b.w, b.h), (200, 20));
        assert_eq!(b.nine_slice, Some((200, 20, 3)));
        assert_eq!(b.file, "gui/sprites/widget/button.png");
        let c = &data.sprites["hud/crosshair"];
        assert_eq!((c.w, c.h), (15, 15));
        assert_eq!(c.nine_slice, None);

        let emitted = emit(&data).unwrap();
        assert!(emitted.contains("name: \"widget/button\""));
        assert!(emitted.contains("Some((200, 20, 3))"));
        assert!(emitted.contains("pub fn sprite(name: &str)"));
    }

    #[test]
    fn inventories_title_textures_from_jar() {
        let mut zip = zip_of(&[
            // real in-jar logo texture
            (
                "assets/minecraft/textures/gui/title/minecraft.png",
                tiny_png(1024, 256),
            ),
            // panorama placeholder (1x1 stub as shipped in 26.2)
            (
                "assets/minecraft/textures/gui/title/background/panorama_0.png",
                tiny_png(1, 1),
            ),
            // directory entry + non-title file must be ignored
            ("assets/minecraft/textures/gui/title/", Vec::new()),
            ("assets/minecraft/textures/env/moon.png", tiny_png(3, 3)),
        ]);
        let data = generate(&mut zip).unwrap();
        let logo = &data.sprites["title/minecraft"];
        assert_eq!((logo.w, logo.h), (1024, 256));
        assert_eq!(logo.file, "gui/title/minecraft.png");
        let pano = &data.sprites["title/background/panorama_0"];
        assert_eq!((pano.w, pano.h), (1, 1));
        assert_eq!(pano.file, "gui/title/background/panorama_0.png");
        assert!(data.sprites.get("env/moon").is_none());
    }

    #[test]
    fn merge_from_disk_overwrite_replaces_stub() {
        let dir = std::env::temp_dir().join(format!("mc2rs-uigen-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("gui/title/background")).unwrap();
        std::fs::write(
            dir.join("gui/title/background/panorama_0.png"),
            tiny_png(1024, 1024),
        )
        .unwrap();
        let names = vec![(
            "title/background/panorama_0".to_string(),
            "gui/title/background/panorama_0.png".to_string(),
        )];

        // stub present, overwrite=false -> stub wins
        let mut data = UiData::default();
        data.sprites.insert(
            "title/background/panorama_0".to_string(),
            Sprite {
                name: "title/background/panorama_0".into(),
                file: "gui/title/background/panorama_0.png".into(),
                w: 1,
                h: 1,
                nine_slice: None,
            },
        );
        merge_from_disk(&mut data, &dir, &names, false).unwrap();
        assert_eq!(data.sprites["title/background/panorama_0"].w, 1);

        // overwrite=true -> real on-disk pixels win
        merge_from_disk(&mut data, &dir, &names, true).unwrap();
        let m = &data.sprites["title/background/panorama_0"];
        assert_eq!((m.w, m.h), (1024, 1024));

        // missing files never insert entries
        let mut fresh = UiData::default();
        merge_from_disk(
            &mut fresh,
            &dir,
            &[("title/nope".to_string(), "gui/title/nope.png".to_string())],
            true,
        )
        .unwrap();
        assert!(fresh.sprites.is_empty());
        std::fs::remove_dir_all(&dir).ok();
    }
}
