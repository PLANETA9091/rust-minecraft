//! Language generation: the full `lang/en_us.json` table becomes a sorted,
//! byte-stable Rust lookup — every UI string the client shows comes from the
//! official language file, not from hand-written literals.

use std::collections::BTreeMap;

use anyhow::{Context, Result};
use serde_json::Value;

use crate::extract::read_entry;

pub struct LangData {
    pub map: BTreeMap<String, String>,
}

pub fn generate(archive: &mut zip::ZipArchive<std::io::Cursor<&[u8]>>) -> Result<LangData> {
    let bytes = read_entry(archive, "assets/minecraft/lang/en_us.json")?;
    let v: Value = serde_json::from_slice(&bytes).context("en_us.json parse")?;
    let obj = v.as_object().context("en_us.json is not an object")?;
    let mut map = BTreeMap::new();
    collect("", obj, &mut map);
    Ok(LangData { map })
}

fn collect(prefix: &str, obj: &serde_json::Map<String, Value>, out: &mut BTreeMap<String, String>) {
    for (k, v) in obj {
        let key = if prefix.is_empty() { k.clone() } else { format!("{prefix}.{k}") };
        match v {
            Value::String(s) => {
                out.insert(key, s.clone());
            }
            Value::Object(inner) => collect(&key, inner, out),
            _ => {} // non-string entries are not translatable text
        }
    }
}

fn rust_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 8);
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

pub fn emit(data: &LangData) -> Result<String> {
    let mut out = String::with_capacity(1 << 20);
    out.push_str("//! GENERATED by mc2rs-gen from the official lang/en_us.json.\n");
    out.push_str("//! Every string is the exact vanilla text; sorted by key for binary search.\n\n");

    out.push_str("pub static LANG_EN_US: [(&str, &str); ");
    out.push_str(&data.map.len().to_string());
    out.push_str("] = [\n");
    for (k, v) in &data.map {
        out.push_str(&format!("    (\"{}\", \"{}\"),\n", rust_escape(k), rust_escape(v)));
    }
    out.push_str("];\n\n");

    out.push_str("/// Translate a GUI key (exact vanilla lookup).\n");
    out.push_str("pub fn tr(key: &str) -> Option<&'static str> {\n");
    out.push_str("    LANG_EN_US.binary_search_by_key(&key, |e| e.0).ok().map(|i| LANG_EN_US[i].1)\n}\n");
    out.push_str("\n/// Translate with fallback to the key itself (vanilla behavior).\n");
    out.push_str("pub fn tr_or(key: &str) -> &'static str {\n    tr(key).unwrap_or(\"MISSING: \")\n}\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn zip_of(entries: &[(&str, Vec<u8>)]) -> zip::ZipArchive<std::io::Cursor<Vec<u8>>> {
        let mut buf = std::io::Cursor::new(Vec::new());
        {
            let mut w = zip::ZipWriter::new(&mut buf);
            let opts = zip::write::SimpleFileOptions::default();
            for (name, data) in entries {
                w.start_file(*name, opts).unwrap();
                std::io::Write::write_all(&mut w, data).unwrap();
            }
            w.finish().unwrap();
        }
        zip::ZipArchive::new(buf).unwrap()
    }

    #[test]
    fn parses_flat_and_nested_keys() {
        let lang = br#"{"menu.singleplayer":"Singleplayer","menu":{"multiplayer":"Multiplayer"},"quote":"He said \"hi\""}"#;
        let mut zip = zip_of(&[("assets/minecraft/lang/en_us.json", lang.to_vec())]);
        let data = generate(&mut zip).unwrap();
        assert_eq!(data.map.get("menu.singleplayer").unwrap(), "Singleplayer");
        assert_eq!(data.map.get("menu.multiplayer").unwrap(), "Multiplayer");
        assert_eq!(data.map.len(), 3);
        let emitted = emit(&data).unwrap();
        assert!(emitted.contains("(\"menu.singleplayer\", \"Singleplayer\")"));
        assert!(emitted.contains("\\\"hi\\\""));
        assert!(emitted.contains("pub fn tr(key: &str) -> Option<&'static str>"));
    }
}
