#!/usr/bin/env python3
"""Emit crates/mc-registry/src/generated/equipment.rs — the humanoid /
humanoid_leggings equipment textures' integrity sha1s + runtime paths,
read verbatim from the local official client jar (26.2). The mc2rs-gen
subcommand's own fold (the skin.rs law) — kept a script until the
generator's next regen pass folds it in.

Usage: python3 scripts/gen_equipment_sha1.py <client.jar> [workspace_root]
"""
import hashlib
import sys
import zipfile

HUMANOID_DIR = "entity/equipment/humanoid"
LEGGINGS_DIR = "entity/equipment/humanoid_leggings"
WINGS_DIR = "entity/equipment/wings"
# The EquipmentAssets registry keys the 26.2 client jar's clinit speaks
# (raw_disasm: LEATHER, COPPER, CHAINMAIL, IRON, GOLD, DIAMOND,
# TURTLE_SCUTE, NETHERITE — the humanoid/humanoid_leggings PNG set the
# equipment/ asset dir carries).
ASSETS = [
    "chainmail",
    "copper",
    "diamond",
    "gold",
    "iron",
    "leather",
    "leather_overlay",
    "netherite",
    "turtle_scute",
]

HEADER = """\
//! GENERATED by mc2rs-gen's equipment fold (scripts/gen_equipment_sha1.py)
//! from the official 26.2 client jar. Source:
//!   assets/minecraft/textures/entity/equipment/(humanoid|humanoid_leggings)/<asset>.png
//! Each sha1 is over the verbatim PNG bytes inside the jar. Do not edit
//! by hand: rerun the script against the jar.

/// The runtime cache dir of the humanoid armor layer's textures (the
/// 26.2 `EquipmentClientInfo.LayerType.HUMANOID` resolution — the
/// helmet/chestplate/boots slots' own draw).
pub const HUMANOID_DIR: &str = "{humanoid_dir}";
/// The leggings slot's texture dir (`LayerType.HUMANOID_LEGGINGS` —
/// the `usesInnerModel` verdict the bytecode speaks).
pub const LEGGINGS_DIR: &str = "{leggings_dir}";

/// One equipment asset's textures: the name (the `Equippable.assetId`
/// the component speaks, sans namespace), the humanoid layer's png
/// sha1, and the leggings layer's — `None` where the asset defines no
/// humanoid_leggings layer (turtle_scute: the helmet's own material).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct EquipmentTex {{
    pub name: &'static str,
    pub humanoid: &'static str,
    pub leggings: Option<&'static str>,
}}

/// The full table, registry order (EquipmentAssets.<clinit>'s own walk).
pub const EQUIPMENT_ASSETS: &[EquipmentTex] = &[
"""


def main() -> None:
    jar_path = sys.argv[1]
    root = sys.argv[2] if len(sys.argv) > 2 else "."
    jar = zipfile.ZipFile(jar_path)
    # THE WINGS LAYER'S OWN TEXTURE (javap WingsLayer + the elytra's
    # equipment/elytra.json the 26.2 jar carries: the WINGS layer
    # type's single row, `texture minecraft:elytra` — the elytra the
    # ONLY root item the wings asset textures; `use_player_texture`
    # true — the player's own skin.elytra()/cape() the
    # getPlayerElytraTexture walk serves instead when the skin carries
    # one, the default steve's neither the elytra.png keeps).
    wings_sha = hashlib.sha1(
        jar.read(f"assets/minecraft/textures/{WINGS_DIR}/elytra.png")
    ).hexdigest()
    rows = []
    for name in ASSETS:
        hu = f"{HUMANOID_DIR}/{name}.png"
        hu_sha = hashlib.sha1(jar.read(f"assets/minecraft/textures/{hu}")).hexdigest()
        lg_path = f"assets/minecraft/textures/{LEGGINGS_DIR}/{name}.png"
        try:
            lg_sha = hashlib.sha1(jar.read(lg_path)).hexdigest()
            lg = f'Some("{lg_sha}")'
        except KeyError:
            lg = "None"
        rows.append(
            f'    EquipmentTex {{ name: "{name}", humanoid: "{hu_sha}", leggings: {lg} }},'
        )
    out = HEADER.format(humanoid_dir=HUMANOID_DIR, leggings_dir=LEGGINGS_DIR)
    out += "\n".join(rows) + "\n];\n\n"
    out += f'''\
/// The wings layer's texture dir (`EquipmentClientInfo.LayerType.WINGS`
/// — the elytra's own equipment/elytra.json the jar carries, the
/// WingsLayer's renderLayers walk the texture resolves).
pub const WINGS_DIR: &str = "{WINGS_DIR}";

/// The wings layer's elytra texture integrity sha1 (the
/// `minecraft:elytra` texture the equipment/elytra.json names, the
/// `use_player_texture` verdict the default no-cape/no-skin-elytra
/// skin keeps). The verbatim PNG bytes inside the jar.
pub const WINGS_ELYTRA_SHA1: &str = "{wings_sha}";

/// The asset table's own lookup — `None` for the names the equipment
/// registry never spoke (the elytra's wings layer the humanoid slots
/// never texture — its own WINGS lane the constants above speak —
/// the client's own honesty).
pub fn find(name: &str) -> Option<&'static EquipmentTex> {{
    EQUIPMENT_ASSETS.iter().find(|t| t.name == name)
}}
'''
    _ = LEGGINGS_DIR  # the emit's own walk keeps both dir consts
    path = f"{root}/crates/mc-registry/src/generated/equipment.rs"
    with open(path, "w") as f:
        f.write(out)
    print(f"equipment: {len(rows)} assets -> {path}")


if __name__ == "__main__":
    main()
